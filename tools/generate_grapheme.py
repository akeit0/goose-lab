"""Generate Unicode 17.0 grapheme properties; normal builds use checked-in output.
Sources are downloaded to build/unicode and verified before generation.
Data copyright Unicode, Inc.; tools/unicode/LICENSE.txt applies.
"""
from pathlib import Path
import hashlib
import urllib.request
ROOT = Path(__file__).resolve().parent.parent
FILES = {
 "GraphemeBreakProperty.txt": ("auxiliary/", "d6b51d1d2ae5c33b451b7ed994b48f1f4dc62b2272a5831e7fd418514a6bae89"),
 "emoji-data.txt": ("emoji/", "2cb2bb9455cda83e8481541ecf5b6dfda66a3bb89efa3fa7c5297eccf607b72b"),
 "DerivedCoreProperties.txt": ("", "24c7fed1195c482faaefd5c1e7eb821c5ee1fb6de07ecdbaa64b56a99da22c08"),
}
CATEGORIES = {"CR":1,"LF":2,"Control":3,"Extend":4,"ZWJ":5,"Regional_Indicator":6,"Prepend":7,"SpacingMark":8,"L":9,"V":10,"T":11,"LV":12,"LVT":13}
values = bytearray(0x110000)
emoji = bytearray(0x110000)
cache = ROOT / "build/unicode"
cache.mkdir(parents=True, exist_ok=True)
for name, (folder, digest) in FILES.items():
 path = cache / name
 if not path.exists():
  path.write_bytes(urllib.request.urlopen("https://www.unicode.org/Public/17.0.0/ucd/" + folder + name, timeout=30).read())
 data = path.read_bytes()
 if hashlib.sha256(data).hexdigest() != digest:
  raise ValueError("Unexpected source digest: " + name)
 for line in data.decode("utf-8").splitlines():
  fields = [v.strip() for v in line.split("#")[0].split(";")]
  if len(fields)<2 or not fields[0]: continue
  flag = CATEGORIES.get(fields[1],0) if name=="GraphemeBreakProperty.txt" else (16 if fields[1]=="Extended_Pictographic" else 0) if name=="emoji-data.txt" else {"Consonant":32,"Linker":64,"Extend":128}.get(fields[2],0) if fields[1]=="InCB" and len(fields)>2 else 0
  span=fields[0].split(".."); start=int(span[0],16); end=int(span[-1],16)
  if name=="emoji-data.txt":
   presentation={"Emoji":1,"Emoji_Presentation":2}.get(fields[1],0)
   if presentation:
    for cp in range(start,end+1): emoji[cp] |= presentation
  if not flag: continue
  for cp in range(start,end+1): values[cp] |= flag
# Hangul syllable LV/LVT alternation has a direct UAX #29 arithmetic rule.
for cp in range(0xAC00,0xD7A4):
 assert values[cp] in (12,13)
 values[cp]=0
packed=bytearray(); cp=0; count=0
while cp<len(values):
 flag=values[cp]; end=cp+1
 while end<len(values) and values[end]==flag: end+=1
 if flag:
  packed += cp.to_bytes(3,"little") + (end-1).to_bytes(3,"little") + bytes([flag]); count+=1
 cp=end
lines=["".join("\\x%02X"%b for b in packed[i:i+84]) for i in range(0,len(packed),84)]
# Multiline literals retain newlines; one literal keeps the packed stride exact.
source="// Generated by tools/generate_grapheme.py; Unicode 17.0.0.\n// Unicode data license: tools/unicode/LICENSE.txt.\nnamespace lab_text_internal_grapheme_data;\nlet DATA: const u8[:] = \"" + "".join(lines) + "\";\n"
(ROOT / "lib/lab/text/internal/grapheme_data.goose").write_text(source,encoding="utf-8",newline="\n")
print(f"{count} ranges, {len(packed)} bytes")
# Native font-run selection uses the exact same pinned Unicode properties.
# Extra high bits select emoji presentation without changing Goose's packed ABI.
ranges=[]; cp=0
while cp<len(values):
 flag=values[cp] | (emoji[cp]<<8); end=cp+1
 while end<len(values) and (values[end] | (emoji[end]<<8))==flag: end+=1
 if flag: ranges.append(f"    {{0x{cp:X},0x{end-1:X},0x{flag:X}}},")
 cp=end
(ROOT / "native/ui/text/internal/unicode_data.h").write_text(
 "// Generated by tools/generate_grapheme.py; Unicode 17.0.0.\n"
 "// Unicode data license: tools/unicode/LICENSE.txt.\n"
 "static const struct { uint32_t first, last; uint16_t flags; } text_unicode_ranges[] = {\n"
 + "\n".join(ranges) + "\n};\n",encoding="utf-8",newline="\n")
